#: The finest resolution a probability report is recorded at. Together with the
#: schema's refusal of 0 and 1, this fixes how extreme a belief can be and still
#: be written down.
REPORT_EPSILON = 1e-9

#: The largest belief magnitude this schema can represent, in log-odds.
#:
#: A simulated log-odds path is unbounded; a recorded probability is not. An
#: earlier version of this module clamped the report to the boundary, which
#: looked harmless and was not: once a path saturates, every later record is the
#: same number, every increment is exactly zero, and the estimators downstream
#: read those zeros as data. In a jump-diffusion recovery study that collapsed
#: the robust scale to a tenth of its true value and flagged 155 of 400
#: increments as jumps. Saturation is now an error, because a belief the
#: instrument cannot represent must not be silently converted into one it can.
MAX_REPRESENTABLE_LOG_ODDS = math.log((1.0 - REPORT_EPSILON) / REPORT_EPSILON)

#: Increments this many robust standard deviations from the diffusive fit are
#: treated as jumps. 4 is conventional and deliberately conservative: missing a
#: jump biases the volatility upward, which is the safer direction for a
#: baseline whose job is to be beaten by a better model.
JUMP_THRESHOLD = 4.0


class SaturatedBeliefError(ValueError):
    """A simulated belief left the range the schema can record."""


def _record(
    path: Sequence[float],
    times: Sequence[float],
    *,
    seed: int,
    evidence_ids: Sequence[str | None] | None = None,
    subject_id: str = "sim-000",
    proposition_id: str = "prop-000",
    code_revision: str = "drl-cfi.baselines",
    config_digest: str = "synthetic",
) -> BeliefTrajectory:
    """Wrap a simulated log-odds path in schema records.

    Simulators return trajectories rather than bare lists so that every path the
    estimators see has already survived the same validation a real record would.
    """
    events = []
    for index, (ell, stamp) in enumerate(zip(path, times, strict=True)):
        if abs(ell) > MAX_REPRESENTABLE_LOG_ODDS:
            raise SaturatedBeliefError(
                f"belief reached log-odds {ell:+.3f} at step {index}, beyond the "
                f"representable +/-{MAX_REPRESENTABLE_LOG_ODDS:.3f}. Recording it "
                f"would pin the report at the boundary and emit zero increments "
                f"that the estimators cannot distinguish from a subject who "
                f"stopped updating. Choose parameters that keep the path in "
                f"range, or shorten the horizon."
            )
        events.append(
            BeliefEvent(
                study_id="cfi-005-recovery",
                run_id=f"seed-{seed}",
                subject_id=subject_id,
                subject_kind=SubjectKind.SIMULATOR,
                model_or_cohort_revision="synthetic-generator",
                task_id="belief-path",
                proposition_id=proposition_id,
                step_index=index,
                event_time=stamp,
                reported_probability=probability(ell),
                action=Action.CONTINUE,
                source_rights_id="synthetic-no-rights-implicated",
                code_revision=code_revision,
                config_digest=config_digest,
                seed=seed,
                maturity=Maturity.SYNTHETIC,
                evidence_id=(
                    evidence_ids[index]
                    if evidence_ids is not None and index < len(evidence_ids)
                    else None
                ),
            )
        )
    return BeliefTrajectory(tuple(events))


def _uniform_times(steps: int, dt: float) -> list[float]:
    return [index * dt for index in range(steps + 1)]


# ---------------------------------------------------------------------------
# 1 and 2. Bayesian updating, exact and asymmetric
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class BayesianFit:
    """Per-evidence log-likelihood ratios recovered from a path."""

    llr_by_evidence: Mapping[str, float]
    residual_scale: float
    observations: int

    def predict(self, evidence_id: str) -> float:
        return self.llr_by_evidence[evidence_id]


@dataclass(frozen=True, slots=True)
class AsymmetricBayesianFit:
    """Separate weights on confirming and disconfirming evidence.

    `confirming_weight == disconfirming_weight == 1` is exact Bayesian updating.
    Departures are readable directly: a confirming weight above one with a
    disconfirming weight below one is the classic asymmetry.
    """

    confirming_weight: float
    disconfirming_weight: float
    residual_scale: float
    observations: int

    @property
    def asymmetry(self) -> float:
        """How far this subject is from exact updating, as a signed gap."""
        return self.confirming_weight - self.disconfirming_weight


def simulate_bayesian(
    nominal_llrs: Sequence[float],
    *,
    seed: int,
    initial_log_odds: float = 0.0,
    report_noise: float = 0.0,
    dt: float = 1.0,
    evidence_ids: Sequence[str] | None = None,
) -> BeliefTrajectory:
    """Exact Bayesian updating: each increment is the evidence's LLR.

    `report_noise` is reporting error, not belief noise — the subject's internal
    posterior is exact and what it says about it is not.
    """
    # S311: a seeded generator is the requirement here, not a weakness — a recovery
    # study is only evidence if it reproduces exactly from its seed.
    rng = random.Random(seed)  # noqa: S311
    ell = initial_log_odds
    path = [ell]
    for llr in nominal_llrs:
        ell = ell + llr
        path.append(ell + (rng.gauss(0.0, report_noise) if report_noise > 0.0 else 0.0))
    ids: list[str | None] = (
        list(evidence_ids)
        if evidence_ids is not None
        else [f"e{index}" for index in range(len(nominal_llrs))]
    )
    return _record(path, _uniform_times(len(nominal_llrs), dt), seed=seed, evidence_ids=ids)


def simulate_asymmetric_bayesian(
    nominal_llrs: Sequence[float],
    *,
    confirming_weight: float,
    disconfirming_weight: float,
    seed: int,
    initial_log_odds: float = 0.0,
    report_noise: float = 0.0,
    dt: float = 1.0,
) -> BeliefTrajectory:
    """Bayesian updating that over- or under-weights by evidence direction."""
    # S311: a seeded generator is the requirement here, not a weakness — a recovery
    # study is only evidence if it reproduces exactly from its seed.
    rng = random.Random(seed)  # noqa: S311
    ell = initial_log_odds
    path = [ell]
    for llr in nominal_llrs:
        weight = confirming_weight if llr > 0.0 else disconfirming_weight
        ell = ell + weight * llr
        path.append(ell + (rng.gauss(0.0, report_noise) if report_noise > 0.0 else 0.0))
    ids: list[str | None] = [f"e{index}" for index in range(len(nominal_llrs))]
    return _record(path, _uniform_times(len(nominal_llrs), dt), seed=seed, evidence_ids=ids)


def fit_bayesian(trajectory: BeliefTrajectory) -> BayesianFit:
    """Recover each evidence item's LLR as the mean increment following it.

    Evidence seen once yields that single increment and a residual of zero,
    which is not evidence of fit. `observations` and `residual_scale` are
    reported so that a reader can see how thin the estimate is.
    """
    increments = trajectory.increments()
    labels = trajectory.evidence_ids()
    grouped: dict[str, list[float]] = {}
    for label, increment in zip(labels, increments, strict=True):
        if label is None:
            continue
        grouped.setdefault(label, []).append(increment)
    if not grouped:
        raise ValueError("no evidence-labelled increments; cannot attribute an LLR")
    estimates = {label: statistics.fmean(values) for label, values in grouped.items()}
    residuals = [
        increment - estimates[label]
        for label, increment in zip(labels, increments, strict=True)
        if label is not None
    ]
    scale = statistics.pstdev(residuals) if len(residuals) > 1 else 0.0
    return BayesianFit(llr_by_evidence=estimates, residual_scale=scale, observations=len(residuals))


def fit_asymmetric_bayesian(
    trajectory: BeliefTrajectory, nominal_llrs: Sequence[float]
) -> AsymmetricBayesianFit:
    """Regress observed increments on the direction-split nominal LLR.

    The two regressors are the positive and negative parts of the nominal LLR,
    so the coefficients are exactly the two weights and no reparameterisation
    stands between the fit and its interpretation.
    """
    increments = trajectory.increments()
    if len(nominal_llrs) != len(increments):
        raise ValueError(
            f"need one nominal LLR per increment; got {len(nominal_llrs)} for "
            f"{len(increments)} increments"
        )
    design = [[max(llr, 0.0), min(llr, 0.0)] for llr in nominal_llrs]
    if all(row[0] == 0.0 for row in design) or all(row[1] == 0.0 for row in design):
        raise ValueError(
            "both confirming and disconfirming evidence are required to separate the two weights"
        )
    confirming, disconfirming = solve_least_squares(design, list(increments))
    residuals = [
        increment - (confirming * row[0] + disconfirming * row[1])
        for row, increment in zip(design, increments, strict=True)
    ]
    scale = statistics.pstdev(residuals) if len(residuals) > 1 else 0.0
    return AsymmetricBayesianFit(
        confirming_weight=confirming,
        disconfirming_weight=disconfirming,
        residual_scale=scale,
        observations=len(increments),
    )


# ---------------------------------------------------------------------------
# 3. Drift-diffusion and Ornstein-Uhlenbeck
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class DiffusionFit:
    """Constant drift and volatility for `dl = mu dt + sigma dW`."""

    drift: float
    volatility: float
    observations: int


@dataclass(frozen=True, slots=True)
class OrnsteinUhlenbeckFit:
    """`dl = theta (m - l) dt + sigma dW`.

    `reversion_rate` at zero is the driftless random walk, so the driftless case
    is nested and the estimate says how far from it the data sit.
    """

    reversion_rate: float
    level: float
    volatility: float
    observations: int

    @property
    def half_life(self) -> float:
        """Time for a displacement to decay by half. Infinite when theta <= 0."""
        if self.reversion_rate <= 0.0:
            return math.inf
        return math.log(2.0) / self.reversion_rate


def simulate_diffusion(
    *,
    drift: float,
    volatility: float,
    steps: int,
    dt: float,
    seed: int,
    initial_log_odds: float = 0.0,
) -> BeliefTrajectory:
    """Brownian motion with drift, in log-odds."""
    # S311: a seeded generator is the requirement here, not a weakness — a recovery
    # study is only evidence if it reproduces exactly from its seed.
    rng = random.Random(seed)  # noqa: S311
    scale = volatility * math.sqrt(dt)
    ell = initial_log_odds
    path = [ell]
    for _ in range(steps):
        ell = ell + drift * dt + rng.gauss(0.0, scale)
        path.append(ell)
    return _record(path, _uniform_times(steps, dt), seed=seed)


def simulate_ornstein_uhlenbeck(
    *,
    reversion_rate: float,
    level: float,
    volatility: float,
    steps: int,
    dt: float,
    seed: int,
    initial_log_odds: float = 0.0,
) -> BeliefTrajectory:
    """Mean-reverting belief, simulated with the exact transition law.

    The exact law is used rather than an Euler step so that the simulator is not
    quietly making the same discretisation approximation as the estimator. If it
    did, the recovery study would be measuring the estimator against its own
    assumption and would look better than it is.
    """
    # S311: a seeded generator is the requirement here, not a weakness — a recovery
    # study is only evidence if it reproduces exactly from its seed.
    rng = random.Random(seed)  # noqa: S311
    decay = math.exp(-reversion_rate * dt)
    if reversion_rate > 0.0:
        stationary = volatility * math.sqrt((1.0 - decay**2) / (2.0 * reversion_rate))
    else:
        stationary = volatility * math.sqrt(dt)
    ell = initial_log_odds
    path = [ell]
    for _ in range(steps):
        ell = level + (ell - level) * decay + rng.gauss(0.0, stationary)
        path.append(ell)
    return _record(path, _uniform_times(steps, dt), seed=seed)


def fit_diffusion(trajectory: BeliefTrajectory) -> DiffusionFit:
    """Maximum-likelihood drift and volatility, tolerating unequal gaps.

    Drift is total displacement over total time; volatility comes from the
    residual increments standardised by their own gap, so a path sampled
    irregularly is not silently mis-scaled.
    """
    increments = trajectory.increments()
    gaps = trajectory.intervals()
    total_time = math.fsum(gaps)
    drift = math.fsum(increments) / total_time
    residual_sq = math.fsum(
        (increment - drift * gap) ** 2 / gap
        for increment, gap in zip(increments, gaps, strict=True)
    )
    volatility = math.sqrt(residual_sq / len(increments))
    return DiffusionFit(drift=drift, volatility=volatility, observations=len(increments))


def fit_ornstein_uhlenbeck(trajectory: BeliefTrajectory) -> OrnsteinUhlenbeckFit:
    """Least-squares OU fit via the Euler form of the drift.

    `Δl = theta·m·dt - theta·l·dt + noise` is linear in two coefficients, so the
    package's own Householder least squares does the work and the parameters
    come back by division. This is the standard discretisation bias: `theta` is
    attenuated as `dt` grows, which the recovery study measures rather than
    hides.
    """
    increments = trajectory.increments()
    gaps = trajectory.intervals()
    levels = trajectory.log_odds_path()[:-1]
    design = [[gap, level * gap] for level, gap in zip(levels, gaps, strict=True)]
    intercept, slope = solve_least_squares(design, list(increments))
    reversion_rate = -slope
    if abs(slope) < 1e-12:
        # No detectable pull: the driftless walk is the honest reading, and the
        # level is unidentified rather than zero.
        level = statistics.fmean(levels)
        reversion_rate = 0.0
    else:
        level = -intercept / slope
    residual_sq = math.fsum(
        (increment - (intercept * gap + slope * lev * gap)) ** 2 / gap
        for increment, lev, gap in zip(increments, levels, gaps, strict=True)
    )
    volatility = math.sqrt(residual_sq / len(increments))
    return OrnsteinUhlenbeckFit(
        reversion_rate=reversion_rate,
        level=level,
        volatility=volatility,
        observations=len(increments),
    )



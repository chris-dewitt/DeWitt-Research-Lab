"""Interpretable belief-dynamics baselines — the CFI-005 reference package.

`COMPUTATIONAL_FINANCE_OF_INTELLIGENCE.md` §2.1 proposes one model family for
belief in log-odds,

```text
dl = mu(l, e, f) dt + sigma(l, e, f) dW + J dN
```

and then says something easy to skip past: *this equation is a model family and
research hypothesis, not a claim that human or machine beliefs actually follow a
diffusion.* This module takes that seriously. It implements the four
interpretable members the bridge starts from, each with a simulator and an
estimator, and it exists to answer one question before any subject is observed:
**when the data really were generated by one of these, does the estimator
recover the parameters that generated them?**

That question has an answer that can be wrong, which is the entire point.
:func:`recovery_study` runs the loop — simulate at known parameters, fit, compare
— and reports the error rather than asserting a threshold. Thresholds belong to
a preregistered protocol, and no protocol has passed G3.

The four baselines, in the order §2.1 lists them:

1. **Exact Bayesian.** In log-odds, Bayes' rule is addition: each piece of
   evidence contributes its log-likelihood ratio and nothing else. The estimator
   recovers a per-evidence LLR.
2. **Asymmetric Bayesian.** The same, with separate weights on confirming and
   disconfirming evidence. `w+ = w- = 1` is the exact case, so the exact model is
   nested inside this one and the gap is directly readable.
3. **Drift-diffusion and Ornstein-Uhlenbeck.** Belief as a random walk, with and
   without pull toward a level. OU nests the driftless walk at `theta = 0`.
4. **Jump-diffusion.** A diffusion plus occasional discrete revisions.

Everything is pure Python, seeded, and deterministic: the same seed gives the
same trajectory on any machine, which is what makes a recovery study a piece of
evidence rather than an anecdote.
"""


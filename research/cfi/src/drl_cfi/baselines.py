# 4. Jump-diffusion
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class JumpDiffusionFit:
    """A diffusion plus discrete revisions, separated by robust thresholding."""

    drift: float
    volatility: float
    jump_intensity: float
    jump_mean: float
    jump_scale: float
    jump_indices: tuple[int, ...]
    observations: int

    @property
    def jump_count(self) -> int:
        return len(self.jump_indices)


def simulate_jump_diffusion(
    *,
    drift: float,
    volatility: float,
    jump_intensity: float,
    jump_mean: float,
    jump_scale: float,
    steps: int,
    dt: float,
    seed: int,
    initial_log_odds: float = 0.0,
) -> BeliefTrajectory:
    """Brownian belief interrupted by Poisson-timed discrete revisions."""
    # S311: a seeded generator is the requirement here, not a weakness — a recovery
    # study is only evidence if it reproduces exactly from its seed.
    rng = random.Random(seed)  # noqa: S311
    diffusive = volatility * math.sqrt(dt)
    jump_probability = 1.0 - math.exp(-jump_intensity * dt)
    ell = initial_log_odds
    path = [ell]
    for _ in range(steps):
        ell = ell + drift * dt + rng.gauss(0.0, diffusive)
        if rng.random() < jump_probability:
            ell = ell + rng.gauss(jump_mean, jump_scale)
        path.append(ell)
    return _record(path, _uniform_times(steps, dt), seed=seed)


def fit_jump_diffusion(
    trajectory: BeliefTrajectory, *, threshold: float = JUMP_THRESHOLD
) -> JumpDiffusionFit:
    """Separate jumps from diffusion by a robust scale, then fit each part.

    The scale comes from the median absolute deviation rather than the standard
    deviation, because the jumps are exactly what would inflate an SD-based
    threshold and hide themselves. With no jumps flagged, this reduces to
    :func:`fit_diffusion` and reports a zero intensity.
    """
    increments = trajectory.increments()
    gaps = trajectory.intervals()
    standardised = [
        increment / math.sqrt(gap) for increment, gap in zip(increments, gaps, strict=True)
    ]
    centre = statistics.median(standardised)
    deviations = [abs(value - centre) for value in standardised]
    mad = statistics.median(deviations)
    # 1.4826 makes the MAD a consistent estimator of sigma for Gaussian data.
    robust_scale = 1.4826 * mad
    if robust_scale <= 0.0:
        robust_scale = statistics.pstdev(standardised) or 1.0

    jump_indices = tuple(
        index
        for index, value in enumerate(standardised)
        if abs(value - centre) > threshold * robust_scale
    )
    jump_set = set(jump_indices)

    diffusive = [
        (increment, gap)
        for index, (increment, gap) in enumerate(zip(increments, gaps, strict=True))
        if index not in jump_set
    ]
    if not diffusive:
        raise ValueError("every increment was flagged as a jump; nothing left to fit")
    diffusive_time = math.fsum(gap for _, gap in diffusive)
    drift = math.fsum(increment for increment, _ in diffusive) / diffusive_time
    residual_sq = math.fsum((increment - drift * gap) ** 2 / gap for increment, gap in diffusive)
    volatility = math.sqrt(residual_sq / len(diffusive))

    total_time = math.fsum(gaps)
    intensity = len(jump_indices) / total_time
    if jump_indices:
        sizes = [increments[index] - drift * gaps[index] for index in jump_indices]
        jump_mean = statistics.fmean(sizes)
        jump_scale = statistics.pstdev(sizes) if len(sizes) > 1 else 0.0
    else:
        jump_mean = 0.0
        jump_scale = 0.0

    return JumpDiffusionFit(
        drift=drift,
        volatility=volatility,
        jump_intensity=intensity,
        jump_mean=jump_mean,
        jump_scale=jump_scale,
        jump_indices=jump_indices,
        observations=len(increments),
    )



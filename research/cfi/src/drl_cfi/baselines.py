@dataclass(frozen=True, slots=True)
class ParameterRecovery:
    """How one parameter's estimate behaved across replications."""

    name: str
    truth: float
    estimates: tuple[float, ...]

    @property
    def mean_estimate(self) -> float:
        return statistics.fmean(self.estimates)

    @property
    def bias(self) -> float:
        """Mean estimate minus truth. Signed, so direction is readable."""
        return self.mean_estimate - self.truth

    @property
    def spread(self) -> float:
        return statistics.pstdev(self.estimates) if len(self.estimates) > 1 else 0.0

    @property
    def root_mean_square_error(self) -> float:
        return math.sqrt(statistics.fmean([(value - self.truth) ** 2 for value in self.estimates]))

    @property
    def relative_bias(self) -> float:
        """Bias as a fraction of truth. Infinite when the truth is zero."""
        if self.truth == 0.0:
            return math.inf if self.bias != 0.0 else 0.0
        return self.bias / abs(self.truth)


@dataclass(frozen=True, slots=True)
class RecoveryReport:
    """The result of simulating at known parameters and fitting them back.

    Deliberately carries no verdict. Whether a bias of 0.03 is acceptable is a
    protocol question, and G3 has not been passed, so this reports and stops.
    """

    model: str
    replications: int
    steps: int
    dt: float
    parameters: tuple[ParameterRecovery, ...]

    def by_name(self, name: str) -> ParameterRecovery:
        for recovery in self.parameters:
            if recovery.name == name:
                return recovery
        raise KeyError(name)

    def worst_relative_bias(self) -> float:
        return max(abs(p.relative_bias) for p in self.parameters)

    def render(self) -> str:
        lines = [
            f"recovery: {self.model}",
            f"  {self.replications} replications, {self.steps} steps, dt={self.dt}",
        ]
        for recovery in self.parameters:
            lines.append(
                f"  {recovery.name:>16}  truth {recovery.truth:+.4f}  "
                f"mean {recovery.mean_estimate:+.4f}  bias {recovery.bias:+.4f}  "
                f"rmse {recovery.root_mean_square_error:.4f}"
            )
        return "\n".join(lines)


def recovery_study(
    model: str,
    *,
    replications: int = 200,
    steps: int = 400,
    dt: float = 0.05,
    seed: int = 20260825,
    **truth: float,
) -> RecoveryReport:
    """Simulate at known parameters, fit, and report the recovery error.

    `model` selects one of `diffusion`, `ornstein_uhlenbeck`, or
    `jump_diffusion`; the remaining keyword arguments are that model's true
    parameters. Each replication uses a distinct derived seed, so the study is
    reproducible in full from the one `seed` given here.
    """
    if replications < 1:
        raise ValueError("a recovery study needs at least one replication")
    collected: dict[str, list[float]] = {}

    def observe(name: str, value: float) -> None:
        collected.setdefault(name, []).append(value)

    for replication in range(replications):
        run_seed = seed + replication
        if model == "diffusion":
            trajectory = simulate_diffusion(
                drift=truth["drift"],
                volatility=truth["volatility"],
                steps=steps,
                dt=dt,
                seed=run_seed,
            )
            fitted = fit_diffusion(trajectory)
            observe("drift", fitted.drift)
            observe("volatility", fitted.volatility)
        elif model == "ornstein_uhlenbeck":
            trajectory = simulate_ornstein_uhlenbeck(
                reversion_rate=truth["reversion_rate"],
                level=truth["level"],
                volatility=truth["volatility"],
                steps=steps,
                dt=dt,
                seed=run_seed,
            )
            ou = fit_ornstein_uhlenbeck(trajectory)
            observe("reversion_rate", ou.reversion_rate)
            observe("level", ou.level)
            observe("volatility", ou.volatility)
        elif model == "jump_diffusion":
            trajectory = simulate_jump_diffusion(
                drift=truth["drift"],
                volatility=truth["volatility"],
                jump_intensity=truth["jump_intensity"],
                jump_mean=truth["jump_mean"],
                jump_scale=truth["jump_scale"],
                steps=steps,
                dt=dt,
                seed=run_seed,
            )
            jd = fit_jump_diffusion(trajectory)
            observe("drift", jd.drift)
            observe("volatility", jd.volatility)
            observe("jump_intensity", jd.jump_intensity)
        else:
            raise ValueError(f"unknown model {model!r}")

    parameters = tuple(
        ParameterRecovery(name=name, truth=truth[name], estimates=tuple(values))
        for name, values in collected.items()
    )
    return RecoveryReport(
        model=model,
        replications=replications,
        steps=steps,
        dt=dt,
        parameters=parameters,
    )
